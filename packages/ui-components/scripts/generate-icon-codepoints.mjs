// Generates src/components/sc-icon/codepoints.ts from @phosphor-icons/web's
// selection.json files: one name → codepoint map per weight (duotone icons are
// glyph PAIRS — a dimmed back layer + a front layer).
//
// Why: importing Phosphor's stock style.css ships ~100 KB of per-icon
// `.ph-*:before` rules per weight into the render-blocking head CSS AND into
// sc-icon's shadow CSSResult (i.e. the boot JS bundle), plus @font-face src
// lists whose woff/ttf/svg fallbacks (~9.4 MB) all land in dist. With the map,
// sc-icon addresses glyphs by codepoint (a CSS custom property), the foundation
// hand-writes woff2-only @font-face rules, and no glyph CSS ships anywhere.
//
// Run from the package root after bumping @phosphor-icons/web:
//   node scripts/generate-icon-codepoints.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const pkgRoot = resolve(fileURLToPath(import.meta.url), "..", "..");

/** Read a weight's selection.json through the package's own resolution. */
function selection(weight) {
  const styleCss = require.resolve(`@phosphor-icons/web/${weight}/style.css`);
  return JSON.parse(readFileSync(resolve(dirname(styleCss), "selection.json"), "utf8"));
}

/** name(s) → value, splitting IcoMoon's comma-separated alias names and
 *  stripping the weight suffix ("acorn-fill" → "acorn"). */
function collect(weight, suffix, toValue) {
  const map = {};
  for (const icon of selection(weight).icons) {
    const props = icon.properties;
    const value = toValue(props);
    for (let name of props.name.split(",").map((n) => n.trim())) {
      if (suffix && name.endsWith(suffix)) name = name.slice(0, -suffix.length);
      map[name] = value;
    }
  }
  return map;
}

const regular = collect("regular", "", (p) => p.code);
const fill = collect("fill", "-fill", (p) => p.code);
// Duotone: `codes` is the [back, front] glyph pair; a few icons are single-glyph.
const duotone = collect("duotone", "-duotone", (p) => p.codes ?? [p.code]);

const out = `// AUTO-GENERATED by scripts/generate-icon-codepoints.mjs — do not edit.
// Phosphor icon name → font codepoint(s), one map per weight (see the script
// header for why this replaces @phosphor-icons/web's per-icon CSS rules).
// Regenerate after bumping @phosphor-icons/web.

export const REGULAR: Readonly<Record<string, number>> = ${JSON.stringify(regular)};

export const FILL: Readonly<Record<string, number>> = ${JSON.stringify(fill)};

/** [back, front] glyph pair (back renders dimmed); single-glyph icons have one entry. */
export const DUOTONE: Readonly<Record<string, readonly number[]>> = ${JSON.stringify(duotone)};
`;

const dest = resolve(pkgRoot, "src/components/sc-icon/codepoints.ts");
writeFileSync(dest, out);
console.log(
  `wrote ${dest}: ${Object.keys(regular).length} regular, ${Object.keys(fill).length} fill, ${
    Object.keys(duotone).length
  } duotone`,
);
