function object(value: unknown, where: string): Record<string, unknown> {
  if (value === null || typeof value !== "object" || Array.isArray(value))
    throw new Error(`${where}: expected object`);
  return value as Record<string, unknown>;
}
function keys(value: Record<string, unknown>, allowed: string[], where: string): void {
  const bad = Object.keys(value).filter((key) => !allowed.includes(key));
  if (bad.length) throw new Error(`${where}: unknown key(s): ${bad.join(", ")}`);
}
function oneOf<T extends string>(value: unknown, allowed: readonly T[], where: string): T {
  if (typeof value !== "string" || !allowed.includes(value as T))
    throw new Error(`${where}: invalid value ${JSON.stringify(value)}`);
  return value as T;
}
function parseSpec(raw: unknown): RegistrySpec {
  const registry = object(raw, "spec");
  keys(registry, ["commands", "replies"], "spec");
  if (!Array.isArray(registry.commands)) throw new Error("spec.commands: expected array");
  const commands = registry.commands.map((rawCommand, ci): CommandSpec => {
    const where = `commands[${ci}]`;
    const command = object(rawCommand, where);
    keys(command, ["address", "struct", "category", "doc", "decode", "fields"], where);
    for (const key of ["address", "struct", "category"] as const)
      if (typeof command[key] !== "string") throw new Error(`${where}.${key}: expected string`);
    if (command.doc !== undefined && typeof command.doc !== "string")
      throw new Error(`${where}.doc: expected string`);
    if (command.decode !== undefined && typeof command.decode !== "boolean")
      throw new Error(`${where}.decode: expected boolean`);
    if (!Array.isArray(command.fields)) throw new Error(`${where}.fields: expected array`);
    const fields = command.fields.map((rawField, fi): FieldSpec => {
      const fw = `${where}.fields[${fi}]`;
      const field = object(rawField, fw);
      keys(field, ["name", "form", "default", "doc"], fw);
      if (typeof field.name !== "string") throw new Error(`${fw}.name: expected string`);
      if (field.doc !== undefined && typeof field.doc !== "string")
        throw new Error(`${fw}.doc: expected string`);
      if (field.default !== undefined && typeof field.default !== "number")
        throw new Error(`${fw}.default: expected number`);
      let form: FieldForm;
      if (field.form === "completion" || field.form === "blob" || field.form === "variadic")
        form = field.form;
      else {
        const fo = object(field.form, `${fw}.form`);
        const formKeys = Object.keys(fo);
        if (formKeys.length !== 1) throw new Error(`${fw}.form: expected exactly one form key`);
        const kind = formKeys[0];
        if (kind === "scalar")
          form = { scalar: oneOf(fo.scalar, ["i32", "f32", "string"], `${fw}.form.scalar`) };
        else if (kind === "optionScalar")
          form = {
            optionScalar: oneOf(fo.optionScalar, ["i32", "f32"], `${fw}.form.optionScalar`),
          };
        else if (kind === "list")
          form = { list: oneOf(fo.list, ["i32", "string", "controlId"], `${fw}.form.list`) };
        else if (kind === "tail") {
          if (!Array.isArray(fo.tail) || !fo.tail.length)
            throw new Error(`${fw}.form.tail: expected non-empty array`);
          form = {
            tail: fo.tail.map((v, i) =>
              oneOf(
                v,
                ["i32", "f32", "string", "controlId", "numericValue", "controlValue", "oscArg"],
                `${fw}.form.tail[${i}]`,
              ),
            ),
          };
        } else if (kind === "setnTail") {
          const st = object(fo.setnTail, `${fw}.form.setnTail`);
          keys(st, ["head", "values"], `${fw}.form.setnTail`);
          form = {
            setnTail: {
              head: oneOf(
                st.head,
                ["i32", "f32", "string", "controlId", "numericValue", "controlValue", "oscArg"],
                `${fw}.form.setnTail.head`,
              ),
              values: oneOf(
                st.values,
                ["i32", "f32", "string", "controlId", "numericValue", "controlValue", "oscArg"],
                `${fw}.form.setnTail.values`,
              ),
            },
          };
        } else throw new Error(`${fw}.form: unknown form ${kind}`);
      }
      return {
        name: field.name,
        form,
        ...(field.default === undefined ? {} : { default: field.default }),
        ...(field.doc === undefined ? {} : { doc: field.doc }),
      };
    });
    return {
      address: command.address as string,
      struct: command.struct as string,
      category: command.category as string,
      fields,
      ...(command.doc === undefined ? {} : { doc: command.doc }),
      ...(command.decode === undefined ? {} : { decode: command.decode }),
    };
  });
  const known = new Set<string>(categories.map(([category]) => category));
  for (const command of commands)
    if (!known.has(command.category))
      throw new Error(`command ${command.struct}: unknown category ${command.category}`);
  return { commands, replies: parseReplies(registry.replies) };
}

const rustType = (type: string): string =>
  ({
    i32: "i32",
    f32: "f32",
    string: "String",
    controlId: "ControlId",
    numericValue: "NumericValue",
    controlValue: "ControlValue",
    oscArg: "OscArg",
  })[type] ??
  (() => {
    throw new Error(`unknown type ${type}`);
  })();
function docs(doc: string | undefined, indent: string): string {
  return doc === undefined
    ? ""
    : doc
        .split("\n")
        .map(
          (line) => `${indent}#[doc = "${line.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"]\n`,
        )
        .join("");
}
function renderCommand(command: CommandSpec): string {
  if (
    command.decode &&
    command.fields.some(
      ({ form }) => typeof form !== "object" || !("scalar" in form) || form.scalar !== "i32",
    )
  )
    throw new Error(`${command.struct}: decode commands may contain only scalar i32 fields`);
  // OSC optionals are positional-trailing: a required field after an
  // optional one would silently shift wire positions whenever the optional
  // is omitted.
  const isOptional = ({ form }: FieldSpec) =>
    form === "completion" || (typeof form === "object" && "optionScalar" in form);
  const firstOptional = command.fields.findIndex(isOptional);
  if (firstOptional !== -1) {
    const offender = command.fields.slice(firstOptional).find((f) => !isOptional(f));
    if (offender)
      throw new Error(
        `${command.struct}: required field "${offender.name}" follows an optional one — optionals must form a trailing run`,
      );
  }
  let out =
    docs(command.doc, "    ") +
    `    "${command.address}" ${command.struct}${command.decode ? " decode" : ""} {\n`;
  for (const field of command.fields) {
    out += docs(field.doc, "        ");
    const form = field.form;
    let declaration: string;
    if (form === "completion" || form === "blob" || form === "variadic")
      declaration = `${form} ${field.name}`;
    else if ("scalar" in form) declaration = `scalar ${field.name}: ${rustType(form.scalar)}`;
    else if ("optionScalar" in form)
      declaration = `opt ${field.name}: ${rustType(form.optionScalar)}`;
    else if ("list" in form) declaration = `list ${field.name}: ${rustType(form.list)}`;
    else if ("tail" in form)
      declaration = `tail ${field.name}: (${form.tail.map(rustType).join(", ")})`;
    else
      declaration = `setn ${field.name}: (${rustType(form.setnTail.head)}, ${rustType(form.setnTail.values)})`;
    out += `        ${declaration},\n`;
  }
  return out + "    }\n";
}

/** Canonicalize through rustfmt (stdin — the @generated skip only applies
 *  to on-disk files) so the committed output always satisfies the repo's
 *  `cargo fmt --check` gate. */
function rustfmt(content: string, rel: string): string {
  const r = spawnSync("rustfmt", ["--edition", "2021", "--emit", "stdout"], {
    input: content,
    encoding: "utf8",
  });
  if (r.error) throw new Error(`rustfmt failed for ${rel}: ${r.error.message}`);
  if (r.status !== 0) throw new Error(`rustfmt failed for ${rel}: ${r.stderr}`);
  return r.stdout;
}

// ── the reply surface (replies/mod.rs) ──────────────────────────────────
//
// Generated from the spec's `replies` section: the regular payload structs,
// the KnownReply enum (every variant a newtype), the ServerReply wrapper and
// the from_message dispatch. Entries flagged `custom` keep their struct +
// parser hand-written in replies/custom.rs; the dispatch routes to
// `Struct::parse`.

type ReplyForm =
  | { scalar: "i32" | "f32" | "f64" | "string" }
  | { optionScalar: "i32" }
  | "extras"
  | "lenPrefixedFloats";
type ReplyFieldSpec = { name: string; form: ReplyForm; lenient?: boolean; doc?: string };
type ReplySpec = {
  address: string;
  variant: string;
  struct: string;
  custom?: boolean;
  doc?: string;
  fields?: ReplyFieldSpec[];
};

function parseReplies(raw: unknown): ReplySpec[] {
  if (!Array.isArray(raw)) throw new Error("spec.replies: expected array");
  return raw.map((rawReply, ri): ReplySpec => {
    const where = `replies[${ri}]`;
    const reply = object(rawReply, where);
    keys(reply, ["address", "variant", "struct", "custom", "doc", "fields"], where);
    for (const key of ["address", "variant", "struct"] as const)
      if (typeof reply[key] !== "string") throw new Error(`${where}.${key}: expected string`);
    if (reply.custom !== undefined && typeof reply.custom !== "boolean")
      throw new Error(`${where}.custom: expected boolean`);
    if (reply.custom) {
      if (reply.fields !== undefined) throw new Error(`${where}: custom replies carry no fields`);
      return {
        address: reply.address as string,
        variant: reply.variant as string,
        struct: reply.struct as string,
        custom: true,
        ...(reply.doc === undefined ? {} : { doc: reply.doc as string }),
      };
    }
    if (!Array.isArray(reply.fields)) throw new Error(`${where}.fields: expected array`);
    const fields = reply.fields.map((rawField, fi): ReplyFieldSpec => {
      const fw = `${where}.fields[${fi}]`;
      const field = object(rawField, fw);
      keys(field, ["name", "form", "lenient", "doc"], fw);
      if (typeof field.name !== "string") throw new Error(`${fw}.name: expected string`);
      let form: ReplyForm;
      if (field.form === "extras" || field.form === "lenPrefixedFloats") form = field.form;
      else {
        const fo = object(field.form, `${fw}.form`);
        if ("scalar" in fo)
          form = { scalar: oneOf(fo.scalar, ["i32", "f32", "f64", "string"], `${fw}.form.scalar`) };
        else if ("optionScalar" in fo)
          form = { optionScalar: oneOf(fo.optionScalar, ["i32"], `${fw}.form.optionScalar`) };
        else throw new Error(`${fw}.form: unknown reply form`);
      }
      return {
        name: field.name,
        form,
        ...(field.lenient === undefined ? {} : { lenient: field.lenient as boolean }),
        ...(field.doc === undefined ? {} : { doc: field.doc as string }),
      };
    });
    // container/optional forms must be trailing (positional wire layout)
    fields.forEach((field, index) => {
      const trailing = field.form === "extras" || field.form === "lenPrefixedFloats";
      if (trailing && index !== fields.length - 1)
        throw new Error(`${where}.${field.name}: this form must be the last field`);
      if (
        typeof field.form === "object" &&
        "optionScalar" in field.form &&
        fields.slice(index + 1).some((f) => typeof f.form === "object" && "scalar" in f.form)
      )
        throw new Error(`${where}.${field.name}: required field after an optional one`);
    });
    return {
      address: reply.address as string,
      variant: reply.variant as string,
      struct: reply.struct as string,
      fields,
      ...(reply.doc === undefined ? {} : { doc: reply.doc as string }),
    };
  });
}

function replyStructField(field: ReplyFieldSpec): string {
  const doc = docs(field.doc, "    ");
  const form = field.form;
  if (form === "extras") return `${doc}    pub ${field.name}: Vec<OscArg>,\n`;
  if (form === "lenPrefixedFloats") return `${doc}    pub ${field.name}: Vec<f32>,\n`;
  if ("optionScalar" in form)
    return (
      doc +
      `    #[serde(default, skip_serializing_if = "Option::is_none")]\n` +
      `    #[cfg_attr(feature = "wasm", tsify(optional))]\n` +
      `    pub ${field.name}: Option<i32>,\n`
    );
  const ty = { i32: "i32", f32: "f32", f64: "f64", string: "String" }[form.scalar];
  return `${doc}    pub ${field.name}: ${ty},\n`;
}

/** The dispatch expression parsing one field at wire position `index`. */
function replyParseExpr(reply: ReplySpec, field: ReplyFieldSpec, index: number): string {
  const addr = `"${reply.address}"`;
  const form = field.form;
  if (form === "extras") return `msg.args.get(${index}..).map(osc_args).unwrap_or_default()`;
  if (form === "lenPrefixedFloats") return `${field.name}`; // bound by the prelude block
  if ("optionScalar" in form) return `msg.args.get(${index}).and_then(as_int)`;
  const take = { i32: "take_int", f32: "take_float", f64: "take_double", string: "take_string" }[
    form.scalar
  ];
  const call = `${take}(&msg, ${index}, ${addr})`;
  return field.lenient ? `${call}.unwrap_or_default()` : `${call}?`;
}

function repliesMod(replies: ReplySpec[]): string {
  let out = `${header}
use serde::{Deserialize, Serialize};
#[cfg(feature = "wasm")]
use tsify::Tsify;

use crate::args::{osc_args, OscArg};
use crate::commands::OtherMsg;
use crate::{CommandError, OscMessage};

mod custom;
pub use custom::*;
pub(crate) use custom::{as_int, take_double, take_float, take_int, take_string};

`;
  // structs (dedup by name; NodeInfo is shared by the /n_* family)
  const seen = new Map<string, string>();
  for (const reply of replies) {
    if (reply.custom) continue;
    const fingerprint = JSON.stringify(reply.fields);
    const prior = seen.get(reply.struct);
    if (prior !== undefined) {
      if (prior !== fingerprint)
        throw new Error(`reply struct ${reply.struct}: conflicting field lists`);
      continue;
    }
    seen.set(reply.struct, fingerprint);
    out += docs(reply.doc, "");
    out += `#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[cfg_attr(feature = "wasm", derive(Tsify))]
#[serde(rename_all = "camelCase")]
pub struct ${reply.struct} {
${reply.fields!.map(replyStructField).join("")}}

`;
  }
  // the enum
  out += `/// Every catalogued server-to-client reply, one variant per address —
/// adjacently tagged like the command side: a decoded reply crosses the
/// wasm boundary as \`{ "address": "/n_go", "args": { …fields } }\`.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[cfg_attr(feature = "wasm", derive(Tsify))]
#[serde(tag = "address", content = "args")]
pub enum KnownReply {
${replies.map((r) => `${docs(r.doc, "    ")}    #[serde(rename = "${r.address}")]\n    ${r.variant}(${r.struct}),\n`).join("")}}

/// A reply in transit: catalogued, or the raw fallback for any address the
/// parser doesn't know (shares [\`OtherMsg\`] with the command side). Plain
/// enum — the wasm boundary serializes each arm itself, so no serde here.
#[derive(Debug, Clone, PartialEq)]
pub enum ServerReply {
    Known(KnownReply),
    Other(OtherMsg),
}

impl ServerReply {
    /// Decode raw OSC reply bytes into a typed variant.
    pub fn decode(bytes: &[u8]) -> Result<Self, CommandError> {
        Self::from_message(OscMessage::decode(bytes)?)
    }

    /// Dispatch an already-decoded message into the typed variant whose
    /// OSC address it matches. Unknown addresses become \`Other(..)\`.
    pub fn from_message(msg: OscMessage) -> Result<Self, CommandError> {
        let known = |k: KnownReply| Ok(Self::Known(k));
        match msg.address.as_str() {
`;
  for (const reply of replies) {
    if (reply.custom) {
      out += `            "${reply.address}" => known(KnownReply::${reply.variant}(${reply.struct}::parse(&msg)?)),\n`;
      continue;
    }
    const lenPrefixed = reply.fields!.find((f) => f.form === "lenPrefixedFloats");
    let prelude = "";
    if (lenPrefixed) {
      const base = reply.fields!.indexOf(lenPrefixed);
      prelude = `{
                // wire: …, N, sample0 … sampleN-1
                let count = take_int(&msg, ${base}, "${reply.address}")? as usize;
                let mut ${lenPrefixed.name} = Vec::with_capacity(count);
                for i in 0..count {
                    ${lenPrefixed.name}.push(take_float(&msg, ${base + 1} + i, "${reply.address}")?);
                }
                `;
    }
    const fields = reply
      .fields!.map((f, i) => `                ${f.name}: ${replyParseExpr(reply, f, i)},`)
      .join("\n");
    const literal = `known(KnownReply::${reply.variant}(${reply.struct} {\n${fields}\n            }))`;
    out += lenPrefixed
      ? `            "${reply.address}" => ${prelude}${literal.replaceAll("\n            ", "\n                ")}\n            }\n`
      : `            "${reply.address}" => ${literal},\n`;
  }
  out += `            _ => Ok(Self::Other(OtherMsg {
                address: msg.address,
                args: osc_args(&msg.args),
            })),
        }
    }
}
`;
  return out;
}

// ── the wasm builder surface (commands/wasm_gen.rs) ─────────────────────
//
// One exported function per command, mirroring the crate's serde value the
// TS side feeds to encode/encodeBundle. Coercion helpers live in the hand
// commands/wasm.rs; the TS signatures ride a typescript_custom_section.

const jsNameOf = (address: string): string =>
  address.slice(1).replace(/[/_.]+(.)/g, (_, c: string) => c.toUpperCase());
const fnIdent = (js: string): string => js.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();
const camel = (snake: string): string =>
  snake.replace(/_([a-z0-9])/g, (_, c: string) => c.toUpperCase());

/** coercer fn + TS type per value type (the polymorphic shapes are lenient). */
const VALUE: Record<Tuple, [string, string]> = {
  i32: ["js_i32", "number"],
  f32: ["js_f32", "number"],
  string: ["js_string", "string"],
  controlId: ["js_control_id", "string | number"],
  numericValue: ["js_numeric_value", "number"],
  controlValue: ["js_control_value", "number | string"],
  oscArg: ["js_osc_arg", "number | string | Uint8Array"],
};

const isOptionalField = ({ form }: FieldSpec) =>
  form === "completion" || (typeof form === "object" && "optionScalar" in form);

function rawStr(s: string): string {
  let hashes = 0;
  while (s.includes(`"${"#".repeat(hashes)}`)) hashes += 1;
  const h = "#".repeat(hashes);
  return `r${h}"${s}"${h}`;
}

function wasmCommand(command: CommandSpec): { rust: string; ts: string } {
  const js = jsNameOf(command.address);
  const fn = fnIdent(js);
  const required = command.fields.filter((f) => !isOptionalField(f));
  const optionals = command.fields.filter(isOptionalField);
  const what = (f: FieldSpec) => `"${js}: ${camel(f.name)}"`;

  // ── params ──
  const params: string[] = required.map((f) => `${f.name}: JsValue`);
  const tsParams: string[] = [];
  for (let i = 0; i < required.length; i++) {
    const f = required[i];
    // containers may be omitted (→ empty) when nothing required follows
    const restOptional = required.slice(i + 1).every((r) => container(r));
    tsParams.push(tsRequiredParam(f, container(f) && restOptional));
  }
  const single = optionals.length === 1 ? optionals[0] : undefined;
  if (single) {
    params.push(`${single.name}: JsValue`);
    tsParams.push(
      single.form === "completion"
        ? `${camel(single.name)}?: Uint8Array`
        : `${camel(single.name)}?: number`,
    );
  } else if (optionals.length > 1) {
    params.push("opts: JsValue");
    const keys = optionals.map((f) =>
      f.form === "completion" ? `${camel(f.name)}?: Uint8Array` : `${camel(f.name)}?: number`,
    );
    tsParams.push(`opts?: { ${keys.join("; ")} }`);
  }

  // ── body ──
  let body = "";
  if (optionals.length > 1) {
    for (const f of optionals) body += `    let ${f.name} = opt_key(&opts, "${camel(f.name)}");\n`;
    // guards: a present optional can't ride behind an absent, unfillable one
    for (let i = 0; i < optionals.length; i++) {
      const f = optionals[i];
      const unfillable = f.form === "completion" || f.default === undefined;
      if (!unfillable) continue;
      for (const later of optionals.slice(i + 1)) {
        body += `    if ${later.name}.is_some() && ${f.name}.is_none() {\n        return Err(JsError::new("${js}: ${camel(later.name)} requires ${camel(f.name)} (it rides later on the wire)"));\n    }\n`;
      }
    }
  }
  if (command.fields.length) {
    const fieldExprs = command.fields.map((f) => `        ${f.name}: ${fieldExpr(f)},\n`).join("");
    body += `    encode_msg(KnownMessage::${command.struct}(${command.struct} {\n${fieldExprs}    }))`;
  } else {
    // unit variant — no payload struct in the enum arm
    body += `    encode_msg(KnownMessage::${command.struct})`;
  }

  function fieldExpr(f: FieldSpec): string {
    const form = f.form;
    if (isOptionalField(f)) {
      const coerce = (v: string) =>
        form === "completion"
          ? `js_blob(${v}, ${what(f)})?`
          : `${VALUE[(form as { optionScalar: Tuple }).optionScalar][0]}(${v}, ${what(f)})?`;
      if (single) {
        return `if ${f.name}.is_undefined() { None } else { Some(${coerce(`&${f.name}`)}) }`;
      }
      // opts-mode: fill the documented default when a later optional forces
      // this slot onto the wire
      const laterFlags = optionals
        .slice(optionals.indexOf(f) + 1)
        .map((l) => `${l.name}.is_some()`);
      const fill =
        f.default !== undefined && laterFlags.length
          ? `if ${laterFlags.join(" || ")} { Some(${f.default}) } else { None }`
          : "None";
      return `match &${f.name} { Some(v) => Some(${coerce("v")}), None => ${fill} }`;
    }
    if (form === "blob") return `js_blob(&${f.name}, ${what(f)})?`;
    if (form === "variadic") return `js_list(&${f.name}, ${what(f)}, js_osc_arg)?`;
    if (typeof form === "object" && "scalar" in form)
      return `${VALUE[form.scalar][0]}(&${f.name}, ${what(f)})?`;
    if (typeof form === "object" && "list" in form)
      return `js_list(&${f.name}, ${what(f)}, ${VALUE[form.list][0]})?`;
    if (typeof form === "object" && "tail" in form) {
      const cs = form.tail.map((t) => VALUE[t][0]);
      if (form.tail.length === 2) return `js_pairs(&${f.name}, ${what(f)}, ${cs[0]}, ${cs[1]})?`;
      if (form.tail.length === 3)
        return `js_triples(&${f.name}, ${what(f)}, ${cs[0]}, ${cs[1]}, ${cs[2]})?`;
      throw new Error(`${command.struct}: unsupported tail arity ${form.tail.length}`);
    }
    if (typeof form === "object" && "setnTail" in form)
      return `js_setn(&${f.name}, ${what(f)}, ${VALUE[form.setnTail.head][0]}, ${VALUE[form.setnTail.values][0]})?`;
    throw new Error(`${command.struct}: unhandled form for wasm builder`);
  }

  function container(f: FieldSpec): boolean {
    const form = f.form;
    return (
      form === "variadic" ||
      (typeof form === "object" && ("list" in form || "tail" in form || "setnTail" in form))
    );
  }

  function tsRequiredParam(f: FieldSpec, optional: boolean): string {
    const form = f.form;
    const q = optional ? "?" : "";
    const name = camel(f.name);
    if (form === "blob") return `${name}: Uint8Array`;
    if (form === "variadic") return `${name}${q}: Array<number | string | Uint8Array>`;
    if (typeof form === "object" && "scalar" in form) return `${name}: ${VALUE[form.scalar][1]}`;
    if (typeof form === "object" && "list" in form)
      return `${name}${q}: Array<${VALUE[form.list][1]}>`;
    if (typeof form === "object" && "tail" in form) {
      const tys = form.tail.map((t) => VALUE[t][1]);
      const tuples = `Array<[${tys.join(", ")}]>`;
      const keyed =
        form.tail.length === 2 && (form.tail[0] === "controlId" || form.tail[0] === "string");
      return `${name}${q}: ${keyed ? `${tuples} | Record<string, ${tys[1]}>` : tuples}`;
    }
    if (typeof form === "object" && "setnTail" in form) {
      const h = VALUE[form.setnTail.head][1];
      const v = VALUE[form.setnTail.values][1];
      return `${name}${q}: Array<[${h}, Array<${v}>]>`;
    }
    throw new Error(`${command.struct}: unhandled form for TS signature`);
  }

  const doc = command.doc ? `/// ${command.doc.split("\n").join(" ")}\n` : "";
  const rust = `${doc}#[wasm_bindgen(js_name = "${js}", skip_typescript)]\npub fn ${fn}(${params.join(", ")}) -> Result<Uint8Array, JsError> {\n${body}\n}\n`;
  const tsDoc = command.doc
    ? `/** \`${command.address}\` — ${command.doc.split("\n")[0]} */\n`
    : "";
  const ts = `${tsDoc}export function ${js}(${tsParams.join(", ")}): Uint8Array;\n`;
  return { rust, ts };
}

function wasmGen(spec: RegistrySpec): string {
  let rust = `${header}\n`;
  let ts = "";
  for (const command of spec.commands) {
    const emitted = wasmCommand(command);
    rust += emitted.rust + "\n";
    ts += emitted.ts;
  }
  rust += `#[wasm_bindgen(typescript_custom_section)]\nconst TS_COMMANDS: &'static str = ${rawStr(ts)};\n`;
  return rust;
}

export function render(): Map<string, string> {
  const specPath = path.join(root, "packages/server-commands/specs/server-commands.json");
  const spec = parseSpec(JSON.parse(readFileSync(specPath, "utf8")));
  const rendered = new Map<string, string>();
  const base = "src-tauri/crates/scserver-commands/src/commands";
  for (const [category, file] of categories) {
    const body = spec.commands
      .filter((command) => command.category === category)
      .map(renderCommand)
      .join("");
    rendered.set(
      `${base}/${file}.rs`,
      `${header}\n#![allow(unused_imports, unused_mut)]\n\nuse rosc::OscType;\nuse serde::{Deserialize, Serialize};\n#[cfg(feature = "wasm")]\nuse tsify::Tsify;\n\nuse crate::args::OscArg;\nuse crate::OscMessage;\n\nuse super::prelude::{ControlId, ControlValue, NumericValue};\n\nsc_commands! {\n${body}}\n`,
    );
  }
  const modules = categories.map(([, file]) => `mod ${file};\npub use ${file}::*;`).join("\n\n");
  const arms = (payload: boolean) =>
    spec.commands
      .filter((command) => Boolean(command.fields.length) === payload)
      .map((command) => `        ${command.struct} "${command.address}",`)
      .join("\n");
  rendered.set(
    `${base}/mod.rs`,
    `${header}\nuse serde::{Deserialize, Serialize};\n#[cfg(feature = "wasm")]\nuse tsify::Tsify;\n\nuse crate::OscMessage;\n\nmod prelude;\npub use prelude::*;\n\n#[cfg(feature = "wasm")]\npub(crate) mod wasm;\n\n${modules}\n\ndefine_known_message! {\n    payload {\n${arms(true)}\n    }\n    unit {\n${arms(false)}\n    }\n}\n`,
  );
  rendered.set(`${base}/wasm_gen.rs`, wasmGen(spec));
  rendered.set("src-tauri/crates/scserver-commands/src/replies/mod.rs", repliesMod(spec.replies));
  for (const [rel, content] of rendered) rendered.set(rel, rustfmt(content, rel));
  return rendered;
}

/** Committed .rs files in the managed dir that render() no longer
 *  produces — e.g. a category removed from the spec would otherwise leave
 *  an orphan module that silently drops out of the generated mod.rs. */
export function strayFiles(): string[] {
  const managed: Array<[string, Set<string>]> = [
    ["src-tauri/crates/scserver-commands/src/commands", new Set(["prelude.rs", "wasm.rs"])],
    ["src-tauri/crates/scserver-commands/src/replies", new Set(["custom.rs"])],
  ];
  const expected = new Set(render().keys());
  const strays: string[] = [];
  for (const [dir, hand] of managed) {
    for (const f of readdirSync(path.join(root, dir))) {
      if (f.endsWith(".rs") && !hand.has(f) && !expected.has(`${dir}/${f}`))
        strays.push(`${dir}/${f}`);
    }
  }
  return strays;
}

function main(): void {
  const args = process.argv.slice(2);
  const check = args.length === 1 && args[0] === "--check";
  if (args.length && !check)
    throw new Error(
      `usage: yarn tsx ${path.relative(root, fileURLToPath(import.meta.url))} [--check]`,
    );
  let mismatch = false;
  for (const [relative, content] of render()) {
    const target = path.join(root, relative);
    let current: string | undefined;
    try {
      current = readFileSync(target, "utf8");
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
    }
    if (current === content) continue;
    if (check) {
      console.log(relative);
      mismatch = true;
    } else {
      writeFileSync(target, content);
      console.log(`wrote ${relative}`);
    }
  }
  for (const stray of strayFiles()) {
    console.error(`stray generated file (not produced by the spec): ${stray}`);
    mismatch = true;
  }
  if (mismatch) process.exitCode = 1;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
