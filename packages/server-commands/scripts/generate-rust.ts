type Scalar = "i32" | "f32" | "string";
type OptionScalar = "i32" | "f32";
type List = "i32" | "string" | "controlId";
type Tuple = "i32" | "f32" | "string" | "controlId" | "numericValue" | "controlValue" | "oscArg";
type FieldForm =
  | { scalar: Scalar }
  | { optionScalar: OptionScalar }
  | "completion"
  | "blob"
  | { list: List }
  | "variadic"
  | { tail: Tuple[] }
  | { setnTail: { head: Tuple; values: Tuple } };
type FieldSpec = { name: string; form: FieldForm; default?: number; doc?: string };
type CommandSpec = {
  address: string;
  struct: string;
  category: string;
  doc?: string;
  decode?: boolean;
  fields: FieldSpec[];
};
type RegistrySpec = { commands: CommandSpec[]; replies: ReplySpec[] };

